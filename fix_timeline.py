import omni.timeline, omni.usd
tl = omni.timeline.get_timeline_interface()
st = omni.usd.get_context().get_stage()
print("BEFORE timeline:", tl.get_start_time(), "->", tl.get_end_time(), "| playing:", tl.is_playing())
print("BEFORE stage codes:", st.GetStartTimeCode(), "->", st.GetEndTimeCode(), "| tps:", st.GetTimeCodesPerSecond())
st.SetStartTimeCode(0)
st.SetEndTimeCode(1000000)
tl.set_start_time(0)
tl.set_end_time(1000000)
tl.set_looping(True)
tl.stop()
tl.play()
print("AFTER timeline:", tl.get_start_time(), "->", tl.get_end_time(), "| playing:", tl.is_playing())
print("saved:", st.GetRootLayer().Save())
