import omni.timeline, omni.usd
tl = omni.timeline.get_timeline_interface()
st = omni.usd.get_context().get_stage()
sess = st.GetSessionLayer()
print("session start/end authored:", sess.HasStartTimeCode(), sess.HasEndTimeCode())
sess.ClearStartTimeCode()
sess.ClearEndTimeCode()
print("stage codes now:", st.GetStartTimeCode(), "->", st.GetEndTimeCode())
tl.set_start_time(0)
tl.set_end_time(1000000)
tl.set_looping(True)
tl.stop()
tl.play()
print("timeline:", tl.get_start_time(), "->", tl.get_end_time(), "| playing:", tl.is_playing())
